#!/usr/bin/env python3
"""
validate_md.py - Validate markdown files generated by arxiv_daily.py.

Checks for content completeness and format correctness.

Usage:
    python3 validate_md.py <file.md> [file2.md ...]
    python3 validate_md.py --dir <directory>
    python3 validate_md.py --dir <directory> --recent 5
    python3 validate_md.py --dir <directory> --all

Exit codes:
    0 - All files pass validation
    1 - One or more files have errors or warnings
"""

import argparse
import re
import sys
from pathlib import Path


# ---------------------------------------------------------------------------
# Data structures
# ---------------------------------------------------------------------------

class Issue:
    """A single validation issue."""

    def __init__(self, level: str, line: int | None, message: str):
        self.level = level  # "error" or "warning"
        self.line = line
        self.message = message

    def __str__(self):
        loc = f"line {self.line}" if self.line else "global"
        return f"[{self.level.upper()}] ({loc}) {message}" if False else f"[{self.level.upper()}] ({loc}) {self.message}"


class ValidationResult:
    """Aggregated result for one file."""

    def __init__(self, path: str):
        self.path = path
        self.errors: list[Issue] = []
        self.warnings: list[Issue] = []

    def error(self, line: int | None, msg: str):
        self.errors.append(Issue("error", line, msg))

    def warn(self, line: int | None, msg: str):
        self.warnings.append(Issue("warning", line, msg))

    @property
    def ok(self) -> bool:
        return len(self.errors) == 0


# ---------------------------------------------------------------------------
# Validators
# ---------------------------------------------------------------------------

VALID_SECTIONS_CN = {"新投稿", "跨领域投稿", "替换投稿"}
SECTION_EN_TO_CN = {
    "New submissions": "新投稿",
    "Cross submissions": "跨领域投稿",
    "Replacement submissions": "替换投稿",
}
SECTION_CN_TO_EN = {v: k for k, v in SECTION_EN_TO_CN.items()}


FILENAME_PATTERN = re.compile(r"^\d{4}-\d{2}-\d{2}-[a-z]+\.[A-Z]+\.md$")


def is_valid_filename(path: Path) -> bool:
    """Check if filename matches expected pattern: YYYY-MM-DD-field.md"""
    return bool(FILENAME_PATTERN.match(path.name))


def validate_file(path: Path) -> ValidationResult:
    """Run all validation checks on a single markdown file."""
    result = ValidationResult(str(path))
    text = path.read_text(encoding="utf-8")
    lines = text.split("\n")

    # --- Front matter ---
    fm_end = validate_front_matter(lines, result)

    # --- Body parsing ---
    if fm_end is not None:
        validate_date_matches_filename(path, lines, fm_end, result)
        validate_body(lines, fm_end, result)

    return result


FILENAME_DATE_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})-")
FRONT_MATTER_DATE_RE = re.compile(r"^date:\s*(\d{4}-\d{2}-\d{2})")


def validate_date_matches_filename(path: Path, lines: list[str], fm_end: int, result: ValidationResult):
    """Require the front-matter date to fall on the filename (listing) date.

    Jekyll builds the post URL from the front-matter date, not the filename. If a
    catch-up run stamps a later day, two posts can share one URL and Jekyll keeps
    only one of them.
    """
    m = FILENAME_DATE_RE.match(path.name)
    if not m:
        return
    file_day = m.group(1)
    for i in range(1, fm_end - 1):
        dm = FRONT_MATTER_DATE_RE.match(lines[i])
        if dm:
            if dm.group(1) != file_day:
                result.error(
                    i + 1,
                    f"front matter date {dm.group(1)} 与文件名日期 {file_day} 不一致"
                    "（Jekyll 按 front matter 日期生成 URL，会与其他文章冲突）",
                )
            return


def validate_front_matter(lines: list[str], result: ValidationResult) -> int | None:
    """Validate YAML front matter. Returns the line index after front matter, or None."""
    if not lines or lines[0].strip() != "---":
        result.error(1, "缺少 front matter 起始分隔符 '---'")
        return None

    # Find closing ---
    end_idx = None
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            end_idx = i
            break

    if end_idx is None:
        result.error(1, "缺少 front matter 结束分隔符 '---'")
        return None

    fm_lines = lines[1:end_idx]
    fm_text = "\n".join(fm_lines)

    # Check required fields
    if not re.search(r'^title:\s*".+"', fm_text, re.MULTILINE):
        result.error(None, "front matter 缺少 title 字段")

    if not re.search(r"^date:\s*\d{4}-\d{2}-\d{2}", fm_text, re.MULTILINE):
        result.error(None, "front matter 缺少 date 字段")

    if not re.search(r"^categories:\s*\[.+\]", fm_text, re.MULTILINE):
        result.error(None, "front matter 缺少 categories 字段")

    return end_idx + 1


def validate_body(lines: list[str], start: int, result: ValidationResult):
    """Validate the body content after front matter."""
    body_lines = lines[start:]
    body_text = "\n".join(body_lines)

    # --- Summary header line ---
    summary_match = re.search(
        r"^(.+?) 领域 (\d+年\d+月\d+日) 共有 (\d+) 篇论文更新：",
        body_text,
        re.MULTILINE,
    )
    if not summary_match:
        result.error(start + 1, "缺少总结行 ('{field} 领域 ... 共有 N 篇论文更新：')")
        declared_total = None
    else:
        declared_total = int(summary_match.group(3))

    # --- Check trend line ---
    if "**整体趋势**" not in body_text:
        result.error(None, "缺少 '**整体趋势**' 行")

    # --- Check accepted papers line ---
    if "**已录用论文**" not in body_text:
        result.error(None, "缺少 '**已录用论文**' 行")

    # --- Check open source papers line ---
    if "**开源论文**" not in body_text:
        result.error(None, "缺少 '**开源论文**' 行")

    # --- Section summaries (bullet list) ---
    section_summary_pattern = re.compile(
        r"^- \*\*(\d+) 篇(新投稿|跨领域投稿|替换投稿)\*\*：",
        re.MULTILINE,
    )
    summary_sections = {}
    for m in section_summary_pattern.finditer(body_text):
        count = int(m.group(1))
        sec_name = m.group(2)
        summary_sections[sec_name] = count

    if not summary_sections:
        result.warn(None, "未找到各 section 的摘要列表")

    # --- Parse paper sections ---
    section_header_pattern = re.compile(
        r"^## (新投稿|跨领域投稿|替换投稿) \((\d+)\)",
        re.MULTILINE,
    )
    sections_found: list[tuple[str, int, int]] = []  # (name, declared_count, position)
    for m in section_header_pattern.finditer(body_text):
        sections_found.append((m.group(1), int(m.group(2)), m.start()))

    if not sections_found:
        result.error(None, "未找到任何论文 section (## 新投稿/跨领域投稿/替换投稿)")
        return

    # --- Validate section summary counts match section header counts ---
    for sec_name, header_count, _ in sections_found:
        if sec_name in summary_sections:
            if summary_sections[sec_name] != header_count:
                result.error(
                    None,
                    f"section '{sec_name}' 的摘要计数 ({summary_sections[sec_name]}) "
                    f"与 section header 计数 ({header_count}) 不一致",
                )

    # --- Parse individual papers ---
    paper_pattern = re.compile(
        r'<h3 id="(\d+)">\[(\d+)\]\s+(.*?)</h3>'
    )
    all_papers = list(paper_pattern.finditer(body_text))

    if not all_papers:
        result.error(None, "未找到任何论文条目 (<h3> 标签)")
        return

    # Check sequential numbering
    seen_nums: list[int] = []
    seen_ids: set[str] = set()
    paper_details: list[dict] = []

    for i, pm in enumerate(all_papers):
        anchor_id = int(pm.group(1))
        display_num = int(pm.group(2))
        title = pm.group(3).strip()

        # Determine paper block range
        paper_start = pm.start()
        paper_end = all_papers[i + 1].start() if i + 1 < len(all_papers) else len(body_text)
        paper_block = body_text[paper_start:paper_end]

        # Line number (approximate)
        line_no = start + body_text[:paper_start].count("\n") + 1

        # Check anchor matches display number
        if anchor_id != display_num:
            result.error(line_no, f"论文 [{display_num}] 的 anchor id ({anchor_id}) 与编号 ({display_num}) 不一致")

        seen_nums.append(display_num)

        # Empty title
        if not title:
            result.error(line_no, f"论文 [{display_num}] 标题为空")

        # arXiv ID
        arxiv_match = re.search(
            r"- \*\*arXiv\*\*:\s*\[(\d+\.\d+)\]\(https://arxiv\.org/abs/(\d+\.\d+)\)",
            paper_block,
        )
        if not arxiv_match:
            result.error(line_no, f"论文 [{display_num}] 缺少有效的 arXiv 链接")
            arxiv_id = None
        else:
            link_text = arxiv_match.group(1)
            link_url_id = arxiv_match.group(2)
            arxiv_id = link_text
            if link_text != link_url_id:
                result.error(line_no, f"论文 [{display_num}] arXiv ID 不一致: 文本 '{link_text}' vs URL '{link_url_id}'")
            if arxiv_id in seen_ids:
                result.error(line_no, f"论文 [{display_num}] arXiv ID {arxiv_id} 重复")
            seen_ids.add(arxiv_id)

        # Authors
        if "- **Authors**:" not in paper_block:
            result.error(line_no, f"论文 [{display_num}] 缺少 Authors 字段")
        else:
            authors_match = re.search(r"- \*\*Authors\*\*:\s*(.*)", paper_block)
            if authors_match and not authors_match.group(1).strip():
                result.warn(line_no, f"论文 [{display_num}] Authors 字段为空")

        # Subjects
        if "- **Subjects**:" not in paper_block:
            result.error(line_no, f"论文 [{display_num}] 缺少 Subjects 字段")
        else:
            subjects_match = re.search(r"- \*\*Subjects\*\*:\s*(.*)", paper_block)
            if subjects_match and not subjects_match.group(1).strip():
                result.warn(line_no, f"论文 [{display_num}] Subjects 字段为空")

        # Summary (required - LLM-generated)
        if "- **Summary**:" not in paper_block:
            result.error(line_no, f"论文 [{display_num}] 缺少 Summary 字段")
        else:
            summary_match = re.search(r"- \*\*Summary\*\*:\s*(.*)", paper_block)
            if summary_match:
                summary_text = summary_match.group(1).strip()
                if not summary_text:
                    result.error(line_no, f"论文 [{display_num}] Summary 为空 (LLM 摘要缺失)")
                elif not summary_text.endswith("。"):
                    result.error(line_no, f"论文 [{display_num}] Summary 未以中文句号结尾 (可能不完整)")
                elif len(summary_text) < 50:
                    result.warn(line_no, f"论文 [{display_num}] Summary 较短 ({len(summary_text)} 字符 < 50)")

        # Tags (required - LLM-generated)
        if "- **Tags**:" not in paper_block:
            result.error(line_no, f"论文 [{display_num}] 缺少 Tags 字段 (LLM 标签缺失)")

        # Cross/Replacement markers
        paper_section = _get_section_for_paper(sections_found, body_text, paper_start)
        if paper_section == "跨领域投稿":
            if "(cross-listed)" not in paper_block:
                result.warn(line_no, f"论文 [{display_num}] 属于跨领域投稿但缺少 (cross-listed) 标记")
        elif paper_section == "替换投稿":
            if "(replaced)" not in paper_block:
                result.warn(line_no, f"论文 [{display_num}] 属于替换投稿但缺少 (replaced) 标记")

        # Venue format check (if present)
        venue_match = re.search(r"- \*\*Venue\*\*:\s*(.*)", paper_block)
        if venue_match:
            venue_val = venue_match.group(1).strip()
            if venue_val and not re.match(r"^[A-Za-z].+\d{4}", venue_val):
                result.warn(line_no, f"论文 [{display_num}] Venue 格式可能不正确: '{venue_val}'")

        # Code URL format check (if present)
        code_match = re.search(r"- \*\*Code\*\*:\s*(.*)", paper_block)
        if code_match:
            code_val = code_match.group(1).strip()
            if code_val and "http" not in code_val:
                result.warn(line_no, f"论文 [{display_num}] Code 字段中未找到有效 URL")

        paper_details.append({
            "num": display_num,
            "arxiv_id": arxiv_id,
            "section": paper_section,
            "line": line_no,
        })

    # --- Sequential numbering check ---
    expected = list(range(1, len(seen_nums) + 1))
    if seen_nums != expected:
        result.error(None, f"论文编号不连续: 期望 {expected[:5]}...{expected[-1]}, 实际 {seen_nums[:5]}...{seen_nums[-1] if seen_nums else '?'}")

    # --- Total count check ---
    actual_total = len(all_papers)
    if declared_total is not None and actual_total != declared_total:
        result.error(
            None,
            f"总结行声明 {declared_total} 篇论文, 实际找到 {actual_total} 篇",
        )

    # --- Per-section count check ---
    for sec_name, declared_count, sec_pos in sections_found:
        # Count papers in this section
        next_sec_pos = len(body_text)
        for other_name, _, other_pos in sections_found:
            if other_pos > sec_pos:
                next_sec_pos = min(next_sec_pos, other_pos)
                break
        section_paper_count = sum(
            1
            for p in paper_details
            if p["section"] == sec_name
        )
        if section_paper_count != declared_count:
            result.warn(
                None,
                f"section '{sec_name}' 声明 {declared_count} 篇, 实际解析到 {section_paper_count} 篇 "
                f"(arxiv 页面可能未展示全部论文)",
            )

    # --- Validate cross-references in accepted/opensource lines ---
    valid_nums = set(seen_nums)

    # Accepted paper references
    accepted_line_match = re.search(r"\*\*已录用论文\*\*：(.*)", body_text)
    if accepted_line_match:
        refs_text = accepted_line_match.group(1)
        if refs_text.strip() != "无":
            ref_nums = [int(n) for n in re.findall(r"\[(\d+)\]", refs_text)]
            for rn in ref_nums:
                if rn not in valid_nums:
                    result.error(None, f"已录用论文中引用了不存在的论文编号 [{rn}]")

    # Open source paper references
    opensource_line_match = re.search(r"\*\*开源论文\*\*：(.*)", body_text)
    if opensource_line_match:
        refs_text = opensource_line_match.group(1)
        if refs_text.strip() != "无":
            ref_nums = [int(n) for n in re.findall(r"\[(\d+)\]", refs_text)]
            for rn in ref_nums:
                if rn not in valid_nums:
                    result.error(None, f"开源论文中引用了不存在的论文编号 [{rn}]")

    # --- Section separator check ---
    separator_count = len(re.findall(r"^---$", body_text, re.MULTILINE))
    expected_separators = len(sections_found)
    if separator_count < expected_separators:
        result.warn(
            None,
            f"section 分隔符 '---' 数量 ({separator_count}) 少于 section 数量 ({expected_separators})",
        )


def _get_section_for_paper(
    sections: list[tuple[str, int, int]], body_text: str, paper_pos: int
) -> str | None:
    """Determine which section a paper belongs to based on position."""
    current_section = None
    for sec_name, _, sec_pos in sections:
        if sec_pos <= paper_pos:
            current_section = sec_name
        else:
            break
    return current_section


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="Validate markdown files generated by arxiv_daily.py"
    )
    parser.add_argument("files", nargs="*", help="Markdown files to validate")
    parser.add_argument("--dir", help="Validate all .md files in a directory")
    parser.add_argument(
        "--all",
        action="store_true",
        help="Check all posts (default: only the most recent dates)",
    )
    parser.add_argument(
        "--recent",
        type=int,
        default=1,
        metavar="N",
        help="Number of most recent dates to check (default: 1)",
    )
    args = parser.parse_args()

    paths: list[Path] = []
    skipped: list[Path] = []
    if args.dir:
        dir_path = Path(args.dir)
        if not dir_path.is_dir():
            print(f"Error: {args.dir} is not a directory", file=sys.stderr)
            sys.exit(2)
        all_valid: list[Path] = []
        for p in sorted(dir_path.glob("*.md")):
            if is_valid_filename(p):
                all_valid.append(p)
            else:
                skipped.append(p)
        if args.all:
            paths.extend(all_valid)
        else:
            dates = sorted({p.name[:10] for p in all_valid}, reverse=True)
            recent_dates = set(dates[:args.recent])
            paths.extend([p for p in all_valid if p.name[:10] in recent_dates])
    if args.files:
        for f in args.files:
            p = Path(f)
            if not p.exists():
                print(f"Error: {f} does not exist", file=sys.stderr)
                sys.exit(2)
            if is_valid_filename(p):
                paths.append(p)
            else:
                skipped.append(p)

    if not paths and not skipped:
        print("No files to validate. Provide files or use --dir.", file=sys.stderr)
        sys.exit(2)

    results: list[ValidationResult] = []
    for path in paths:
        results.append(validate_file(path))

    # Sort: FAIL first, then WARN, then PASS
    def _sort_key(r: ValidationResult) -> int:
        if not r.ok:
            return 0
        if r.warnings:
            return 1
        return 2

    results.sort(key=_sort_key)

    has_errors = False
    for result in results:
        if result.ok and not result.warnings:
            print(f"PASS  {result.path}")
        elif result.ok:
            print(f"WARN  {result.path}")
        else:
            print(f"FAIL  {result.path}")
            has_errors = True

        for issue in result.errors + result.warnings:
            print(f"  {issue}")

    # Summary
    print()
    total = len(results)
    failed = sum(1 for r in results if not r.ok)
    warned = sum(1 for r in results if r.ok and r.warnings)
    passed = total - failed - warned
    print(f"Total: {total} files, {passed} passed, {warned} warnings only, {failed} failed")

    if skipped:
        print(f"\nSkipped {len(skipped)} file(s) with non-conforming filenames:")
        for p in skipped:
            print(f"  {p}")

    sys.exit(1 if has_errors else 0)


if __name__ == "__main__":
    main()
